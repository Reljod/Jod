#!/usr/bin/env python3
"""Turn out/*.json into out/SUMMARY.md. Do not hand-edit the result."""

import glob
import json
import os
import sys

ORDER = ["1k", "10k", "100k", "1m"]


def load(outdir):
    got = {}
    for p in glob.glob(os.path.join(outdir, "sqlite-*.json")):
        d = json.load(open(p))
        got[d["label"]] = d
    return got


def cell(v):
    return "—" if v is None else str(v)


def main(outdir):
    got = load(outdir)
    labels = [l for l in ORDER if l in got]
    w = []
    p = w.append

    p("# Measured results\n")
    p("*Generated by `bench/summarize.py`. Do not hand-edit.*\n")
    p("Host: 4 vCPU / 11 GB Linux, SQLite %s via python3 `sqlite3`. "
      "A query exceeding **10 s** was interrupted and is recorded at 10000 ms; "
      "those cells are marked.\n" % got[labels[0]]["sqlite_version"])

    p("\n## Scale\n")
    p("| scale | nodes | edges | facts | db size | max degree |")
    p("|---|---|---|---|---|---|")
    for l in labels:
        d = got[l]
        p("| %s | %d | %d | %d | %.1f MB | %d |" % (
            l, d["nodes"], d["edges"], d["facts"], d["bytes"] / 1e6,
            d["hub_degrees"][0]))

    p("\n## k-hop neighbourhood — p50 / p95 ms\n")
    p("`random` is a uniformly chosen entity; `hub` is one of the "
      "highest-degree entities — the case an average hides.\n")
    keys = [k for k in got[labels[0]]["khop"]]
    p("| query | " + " | ".join(labels) + " |")
    p("|---|" + "---|" * len(labels))
    for k in keys:
        row = []
        for l in labels:
            v = got[l]["khop"].get(k)
            if not v:
                row.append("—")
                continue
            mark = " ⏱" if v.get("timeouts") else ""
            row.append("%s / %s%s" % (cell(v["p50_ms"]), cell(v["p95_ms"]),
                                      mark))
        p("| `%s` | %s |" % (k, " | ".join(row)))

    p("\n## k-hop result size — mean rows returned (and % of all nodes)\n")
    p("| query | " + " | ".join(labels) + " |")
    p("|---|" + "---|" * len(labels))
    for k in keys:
        row = []
        for l in labels:
            v = got[l]["khop"].get(k)
            n = got[l]["nodes"]
            row.append("%.0f (%.0f%%)" % (v["mean_rows"],
                                          100.0 * v["mean_rows"] / n)
                       if v else "—")
        p("| `%s` | %s |" % (k, " | ".join(row)))

    p("\n## Temporal (as-of) 3-hop vs plain 3-hop — p50 ms\n")
    p("| query | " + " | ".join(labels) + " |")
    p("|---|" + "---|" * len(labels))
    for k in ("asof.k3.random", "asof.k3.hub"):
        row = [cell(got[l]["temporal"][k]["p50_ms"]) for l in labels]
        p("| `%s` | %s |" % (k, " | ".join(row)))
    for k in ("directed.k3.random", "directed.k3.hub"):
        row = [cell(got[l]["khop"][k]["p50_ms"]) for l in labels]
        p("| `%s` (no filter) | %s |" % (k, " | ".join(row)))

    p("\n## Shortest path — p50 / p95 ms\n")
    p("| method | " + " | ".join(labels) + " |")
    p("|---|" + "---|" * len(labels))
    for k in ("cte_distance_d5", "cte_path_d5", "bidi_bfs_d6"):
        row = []
        for l in labels:
            v = got[l]["shortest_path"][k]
            mark = " ⏱%d" % v["timeouts"] if v.get("timeouts") else ""
            row.append("%s / %s%s" % (cell(v["p50_ms"]), cell(v["p95_ms"]),
                                      mark))
        p("| `%s` | %s |" % (k, " | ".join(row)))

    p("\n## Retrieval — p50 / p95 ms\n")
    p("| query | " + " | ".join(labels) + " |")
    p("|---|" + "---|" * len(labels))
    for k in ("fts_only", "hybrid"):
        row = []
        for l in labels:
            v = got[l][k]
            mark = " ⏱" if v.get("timeouts") else ""
            row.append("%s / %s%s" % (cell(v["p50_ms"]), cell(v["p95_ms"]),
                                      mark))
        p("| `%s` | %s |" % (k, " | ".join(row)))

    p("\n## Community detection — one label-propagation pass, ms\n")
    p("| scale | p50 | max | timed out |")
    p("|---|---|---|---|")
    for l in labels:
        v = got[l]["label_propagation"]
        p("| %s | %s | %s | %d |" % (l, cell(v["p50_ms"]), cell(v["max_ms"]),
                                     v.get("timeouts", 0)))

    p("\n## Size breakdown\n")
    p("| scale | edges table | ix_edges_out | ix_edges_in | ix_edges_fact | "
      "facts | fts5 total |")
    p("|---|---|---|---|---|---|---|")
    for l in labels:
        s = got[l].get("size_by_object") or {}
        def g(n):
            return "%.1f MB" % (s.get(n, 0) / 1e6) if s else "—"
        fts = sum(v for k, v in s.items() if k.startswith("facts_fts"))
        p("| %s | %s | %s | %s | %s | %s | %.1f MB |" % (
            l, g("edges"), g("ix_edges_out"), g("ix_edges_in"),
            g("ix_edges_fact"), g("facts"), fts / 1e6))

    for extra, title in (("outdegree-100k.json",
                          "k-hop out of the highest out-degree entities"),
                         ("concurrency-100k.json", "Concurrency (100k)"),
                         ("engines-100k.json", "Other engines (100k)"),
                         ("graphqlite-10k.json", "GraphQLite extension (10k)"),
                         ("vectors.json", "sqlite-vec brute force")):
        path = os.path.join(outdir, extra)
        if os.path.exists(path):
            p("\n## %s\n" % title)
            p("```json")
            p(json.dumps(json.load(open(path)), indent=2))
            p("```")

    print("\n".join(w))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "out")
